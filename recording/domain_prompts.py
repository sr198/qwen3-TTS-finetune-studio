def _amount(r):
    rupees = r.choice([r.randint(10, 999), r.randint(1000, 99999),
                       r.randint(100000, 9999999), r.randrange(500, 100000, 500)])
    paisa = r.choice([0, 0, 0, 25, 50, r.randint(1, 99)])
    return amount_to_words(rupees, paisa)


def _date(r, with_year=None):
    y = r.choice([2080, 2081, 2082, 2083])
    return bs_date_to_words(y, r.randint(1, 12), r.randint(1, 30),
                            r.random() < 0.5 if with_year is None else with_year)


def _time(r):
    return time_to_words(r.randint(7, 19), r.choice([0, 0, 15, 30, 45, r.randrange(5, 60, 5)]))


def _mobile(r):
    return digits_to_words(r.choice(["98", "97", "96"]) + "".join(str(r.randint(0, 9)) for _ in range(8)))


def _digits(r, n):
    return digits_to_words("".join(str(r.randint(0, 9)) for _ in range(n)))


