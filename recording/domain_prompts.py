def build(n_templated: int = 400, seed: int = 0):
    """Return list of (category, text). Fixed sentences once each, templates sampled round-robin."""
    r = random.Random(seed)
    out = [(cat, t) for cat, items in FIXED.items() for t in items]
    seen = {t for _, t in out}
    i = 0
    while i < n_templated:
        cat, fn = TEMPLATES[i % len(TEMPLATES)]
        t = fn(r)
        if t not in seen:
            seen.add(t)
            out.append((cat, t))
        i += 1
    return out
